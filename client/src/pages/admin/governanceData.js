//     compliant, and "no conflict detected" is not "placement verified compliant".
//   · EXCEPTIONS NEVER CHANGE THE BASELINE — an excepted requirement stays visible as
//     unsatisfied, so compliant-by-design and operating-under-exception never look alike.

