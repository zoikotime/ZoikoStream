// SCREAMING_SNAKE identifier -> display label, with an override map for the cases where
// sentence-casing is wrong. An unmapped value renders converted rather than as "Unknown":
// coercing a state the registry gave us into Unknown is the exact lie the state-separation
// rules exist to prevent.
//
// Kept local so this module stays a dependency-free payload — it is data, and data importing UI
// formatting helpers is the wrong direction (it also lets `node --test` load it directly).
const toLabel = (v, overrides) =>
  overrides[v] || (v ? v.charAt(0) + v.slice(1).toLowerCase().replace(/_/g, " ") : "—");
export const label = (v) => toLabel(v, LABEL);

