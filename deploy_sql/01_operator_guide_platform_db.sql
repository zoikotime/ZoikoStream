-- Operator Guide (console assistant) tables — run against the PLATFORM database (DATABASE_URL).
-- Additive and idempotent: creates 6 new opguide_* tables only; no existing table is altered.
-- Equivalent to: cd server && python -m app.operator_guide.schema
BEGIN;

CREATE TABLE IF NOT EXISTS opguide_audit (
	id BIGINT GENERATED BY DEFAULT AS IDENTITY, 
	interaction_id VARCHAR(64) NOT NULL, 
	org_id UUID NOT NULL, 
	actor_id UUID NOT NULL, 
	role_context VARCHAR(32) NOT NULL, 
	context JSONB NOT NULL, 
	kind VARCHAR(32) NOT NULL, 
	user_request_hash VARCHAR(64), 
	intent VARCHAR(48), 
	model_release VARCHAR(96), 
	policy_version VARCHAR(32) NOT NULL, 
	retrieval_source_refs JSONB NOT NULL, 
	tool_plan JSONB NOT NULL, 
	authorization_result VARCHAR(32), 
	tool_execution_receipts JSONB NOT NULL, 
	confirmation_actor UUID, 
	correlation_id VARCHAR(64), 
	final_response_ref VARCHAR(64), 
	outcome VARCHAR(32) NOT NULL, 
	latency_ms INTEGER, 
	created_at TIMESTAMP WITH TIME ZONE DEFAULT now() NOT NULL, 
	purge_after TIMESTAMP WITH TIME ZONE NOT NULL, 
	PRIMARY KEY (id)
);

CREATE INDEX IF NOT EXISTS ix_opguide_audit_corr ON opguide_audit (correlation_id);
CREATE INDEX IF NOT EXISTS ix_opguide_audit_org ON opguide_audit (org_id, created_at DESC);
CREATE INDEX IF NOT EXISTS ix_opguide_audit_purge ON opguide_audit (purge_after);

CREATE TABLE IF NOT EXISTS opguide_conversations (
	id UUID NOT NULL, 
	org_id UUID NOT NULL, 
	user_id UUID NOT NULL, 
	title VARCHAR(160) NOT NULL, 
	context JSONB NOT NULL, 
	created_at TIMESTAMP WITH TIME ZONE DEFAULT now() NOT NULL, 
	updated_at TIMESTAMP WITH TIME ZONE DEFAULT now() NOT NULL, 
	archived_at TIMESTAMP WITH TIME ZONE, 
	purge_after TIMESTAMP WITH TIME ZONE NOT NULL, 
	PRIMARY KEY (id)
);

CREATE INDEX IF NOT EXISTS ix_opguide_conv_owner ON opguide_conversations (org_id, user_id, updated_at DESC);
CREATE INDEX IF NOT EXISTS ix_opguide_conv_purge ON opguide_conversations (purge_after);

CREATE TABLE IF NOT EXISTS opguide_proposals (
	id UUID NOT NULL, 
	org_id UUID NOT NULL, 
	actor_id UUID NOT NULL, 
	conversation_id UUID, 
	action_id VARCHAR(64) NOT NULL, 
	risk_class VARCHAR(4) NOT NULL, 
	target_type VARCHAR(32) NOT NULL, 
	target_id VARCHAR(64) NOT NULL, 
	params JSONB NOT NULL, 
	summary JSONB NOT NULL, 
	status VARCHAR(16) NOT NULL, 
	idempotency_key VARCHAR(128), 
	correlation_id VARCHAR(64) NOT NULL, 
	receipt JSONB, 
	confirmed_by UUID, 
	confirmed_at TIMESTAMP WITH TIME ZONE, 
	executed_at TIMESTAMP WITH TIME ZONE, 
	expires_at TIMESTAMP WITH TIME ZONE NOT NULL, 
	created_at TIMESTAMP WITH TIME ZONE DEFAULT now() NOT NULL, 
	PRIMARY KEY (id)
);

CREATE INDEX IF NOT EXISTS ix_opguide_prop_owner ON opguide_proposals (org_id, actor_id, created_at DESC);
CREATE UNIQUE INDEX IF NOT EXISTS uq_opguide_prop_idem ON opguide_proposals (org_id, idempotency_key) WHERE idempotency_key IS NOT NULL;

CREATE TABLE IF NOT EXISTS opguide_settings (
	org_id UUID NOT NULL, 
	enabled BOOLEAN NOT NULL, 
	capabilities JSONB NOT NULL, 
	updated_by UUID, 
	updated_at TIMESTAMP WITH TIME ZONE DEFAULT now() NOT NULL, 
	PRIMARY KEY (org_id)
);


CREATE TABLE IF NOT EXISTS opguide_messages (
	id UUID NOT NULL, 
	conversation_id UUID NOT NULL, 
	role VARCHAR(16) NOT NULL, 
	text TEXT NOT NULL, 
	payload JSONB NOT NULL, 
	intent VARCHAR(48), 
	created_at TIMESTAMP WITH TIME ZONE DEFAULT now() NOT NULL, 
	PRIMARY KEY (id), 
	FOREIGN KEY(conversation_id) REFERENCES opguide_conversations (id) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS ix_opguide_msg_conv ON opguide_messages (conversation_id, created_at);

CREATE TABLE IF NOT EXISTS opguide_feedback (
	id UUID NOT NULL, 
	message_id UUID NOT NULL, 
	org_id UUID NOT NULL, 
	user_id UUID NOT NULL, 
	rating VARCHAR(8) NOT NULL, 
	reason VARCHAR(32), 
	created_at TIMESTAMP WITH TIME ZONE DEFAULT now() NOT NULL, 
	PRIMARY KEY (id), 
	FOREIGN KEY(message_id) REFERENCES opguide_messages (id) ON DELETE CASCADE
);

CREATE UNIQUE INDEX IF NOT EXISTS uq_opguide_feedback ON opguide_feedback (message_id, user_id);

COMMIT;
